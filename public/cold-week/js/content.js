/** سلامة المحتوى (تُستعمل في الاختبار): كل موقف حلّه بطاقة جيدة، ومشتّتاته موجودة ومختلفة عن الحل. */
export function validate() {
  const errs = [];
  for (const s of SITUATIONS) {
    if (!CARDS[s.answer]?.good) errs.push(`${s.id}: الحل ليس بطاقة جيدة`);
    if (s.others.length !== 3) errs.push(`${s.id}: يحتاج ٣ مشتّتات`);
    for (const o of s.others) {
      if (!CARDS[o]) errs.push(`${s.id}: بطاقة غير موجودة ${o}`);
      if (o === s.answer) errs.push(`${s.id}: المشتّت هو الحل`);
    }
    if (new Set(s.others).size !== 3) errs.push(`${s.id}: مشتّت مكرر`);
    if (!DOLLS[s.doll] || !DOLLS[s.near] || s.doll === s.near) errs.push(`${s.id}: دمية غير صحيحة`);
    if (!TOPICS[s.topic]) errs.push(`${s.id}: موضوع غير معروف`);
  }
  return errs;
}
