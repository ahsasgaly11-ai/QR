// ميزانية الرسم مع الكاميرا. تتبّع اليد (نموذج MediaPipe على معالج الرسوم + فيديو
// 1080p) يستهلك ذاكرة معالج الرسوم نفسها التي يرسم بها المشهد ثلاثي الأبعاد؛ إن
// تجاوز المجموع حدّ Safari على الآيباد انهارت الصفحة («حدثت مشكلة بشكل متكرر»).
// لذا حين تعمل الكاميرا (app.js يضبط <html data-camera="on">) تخفّض الألعاب دقة
// البكسل وحدّ البكسلات الكلي؛ الأهداف والمواضع لا تتغيّر.
// ---------------------------------------------------------------------------

/** هل الكاميرا تعمل الآن (تتبّع اليد نشط أو قيد التشغيل)؟ */
export const cameraOn = () => document.documentElement.dataset.camera === 'on';

/**
 * سقف دقة البكسل وحدّ البكسلات مع مراعاة الكاميرا.
 * @param {number} dprCap سقف الطبقة بلا كاميرا (مثل 1.5)
 * @param {number} maxPx حدّ البكسلات بلا كاميرا (مثل 2.6e6)
 */
export function cameraBudget(dprCap, maxPx) {
  if (!cameraOn()) return { dprCap, maxPx };
  return { dprCap: Math.min(dprCap, 1.1), maxPx: Math.min(maxPx, 1.5e6) };
}
