// نموذج الغلوس الإشاري — الطبقة الذكية فوق القاموس
//
// القاموس وحده يطابق الكلمة كما كُتبت. هذه الطبقة تحوّل النصّ العربي إلى
// «غلوس» إشاري: تسلسل من مفاتيح القاموس بترتيب إشاري، بعد تجريد الكلمة من
// تصريفها (طلبة ← طالب، يصنّف ← تصنيف، مواد ← مادة)، واختيار المرادف المتاح
// حين يحفظ المعنى، وحذف الأدوات التي لا إشارة لها (أل التعريف، الرابط)، ووضع
// أداة الاستفهام في موضعها الإشاري. المخرج **مقيّد بمفردات القاموس**: كل مفتاح
// يجب أن يكون موجودًا فعلًا، وما لا إشارة له يُعلَّم للتهجئة.
//
// ثلاث طبقات بترتيب الأفضلية:
//   1) غلوس محسوب مسبقًا (public/sign/gloss-cache.json) — صفر تكلفة وقت التشغيل.
//   2) غلوس من الخادم (/api/sign/gloss) عبر Claude، مع تخزين في Firestore.
//   3) الوضع الحرفي: كلمةً كلمة (buildSequence) — يعمل دائمًا بلا شبكة.
//
// صدق: الغلوس ترتيب إشاري تقريبي من نموذج لغوي بانتظار اعتماد مترجم، ويُعلَن
// ذلك في المشغّل، ويستطيع الطالب التبديل إلى الوضع الحرفي.
// ---------------------------------------------------------------------------

import { z } from 'zod/v4';

/** عنصر واحد في الغلوس: إشارة من القاموس، أو كلمة تُهجّى. */
export const GlossItemSchema = z.object({
  /** مفتاح الإشارة في القاموس (مُطبَّع)، أو سلسلة فارغة إن كانت الكلمة تُهجّى. */
  key: z.string(),
  /** الكلمة/العبارة الأصلية في النصّ كما كُتبت (للعرض والإبراز). */
  word: z.string(),
  /** فهرسا أوّل وآخر كلمة في النصّ الأصلي تغطّيهما هذه الإشارة (بالترتيب من 0). */
  from: z.number().int().min(0),
  to: z.number().int().min(0),
  /** الكلمة التي تُهجّى حين لا إشارة (key فارغ): بلا تشكيل ولا أداة تعريف. */
  spell: z.string().optional(),
});

export const GlossSchema = z.object({
  items: z.array(GlossItemSchema),
  /** ملاحظة قصيرة من النموذج عن قرارات الترتيب أو المرادفات (للمراجع). */
  note: z.string().optional(),
});

export type GlossItem = z.infer<typeof GlossItemSchema>;
export type Gloss = z.infer<typeof GlossSchema>;

export const GLOSS_VERSION = 2;

// علامات التشكيل، مطابقة لمحرّك الإشارة.
const MARKS = /[ً-ْٰـ]/g;
export function normalizeKey(s: string): string {
  return s
    .trim()
    .replace(MARKS, '')
    .replace(/[٠-٩]/g, (d) => String(d.charCodeAt(0) - 0x660))
    .replace(/[إأآٱ]/g, 'ا')
    .replace(/ى/g, 'ي')
    .replace(/ؤ/g, 'و')
    .replace(/ئ/g, 'ي')
    .replace(/ة/g, 'ه')
    .toLowerCase();
}

/** مفتاح تخزين مستقرّ للنصّ (FNV-1a 32 بت على النصّ المُطبَّع). */
export function glossCacheKey(text: string): string {
  const s = `${GLOSS_VERSION}|${normalizeKey(text).replace(/\s+/g, ' ')}`;
  let h = 0x811c9dc5;
  for (let i = 0; i < s.length; i++) {
    h ^= s.charCodeAt(i);
    h = Math.imul(h, 0x01000193) >>> 0;
  }
  return h.toString(16).padStart(8, '0');
}

/** يتحقّق من أن كل مفتاح في الغلوس موجود في القاموس، ويُسقط ما ليس كذلك إلى التهجئة. */
export function sanitizeGloss(g: Gloss, vocab: Set<string>, wordCount: number): Gloss {
  const items: GlossItem[] = [];
  for (const it of g.items) {
    const from = Math.max(0, Math.min(wordCount - 1, it.from));
    const to = Math.max(from, Math.min(wordCount - 1, it.to));
    const key = normalizeKey(it.key || '');
    // مفتاح مركّب أطول من الكلمات التي يغطّيها يضيف معنى ليس في النصّ
    if (key && vocab.has(key) && key.split(/\s+/).length <= to - from + 1) {
      items.push({ ...it, key, from, to });
    } else {
      // لا نلفّق إشارة: نُهجّي الكلمة الأصلية
      items.push({ key: '', word: it.word, from, to, spell: it.spell || it.word });
    }
  }
  return { items, note: g.note };
}

