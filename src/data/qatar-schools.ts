function jitter(id: string): [number, number] {
  const h = hashString(id);
  const a = ((h & 0xffff) / 0xffff) * 2 - 1;
  const b = (((h >>> 16) & 0xffff) / 0xffff) * 2 - 1;
  return [a, b];
}

// --- بناء قائمة المدارس النهائية (دمج + إزالة التكرار بالاسم) ----------------
export const QATAR_SCHOOLS: QatarSchool[] = (() => {
  const out: QatarSchool[] = [];
  const seen = new Set<string>();
  const key = (name: string) => normalizeArabic(name);

  // 1) مدارس GIS الرسمية (إحداثيات فعلية + بلدية مُتحقّقة).
  GIS_SCHOOLS.forEach(([name, gender, stage, mun, lat, lng], i) => {
    const k = key(name);
    if (seen.has(k)) return;
    seen.add(k);
    out.push({
      id: `gis-${i}-${hashString(name).toString(36)}`,
      name,
      municipalityId: mun,
      gender,
      stage,
      lat,
      lng,
      real: true,
    });
  });

  // 2) الأسماء التكميلية (إحداثيات من مركز البلدية + إزاحة).
  EXTRA_SCHOOLS.forEach(([name, gender, stage, mun, approx], i) => {
    const k = key(name);
    if (seen.has(k)) return;
    seen.add(k);
    const base = MUNICIPALITY_BY_ID[mun];
    const id = `ex-${i}-${hashString(name).toString(36)}`;
    const [ja, jb] = jitter(id);
    out.push({
      id,
      name,
      municipalityId: mun,
      gender,
      stage,
      lat: +(base.lat + jb * base.spread * 0.8).toFixed(4),
      lng: +(base.lng + ja * base.spread).toFixed(4),
      ...(approx ? { approx: true } : {}),
    });
  });

  return out;
})();

